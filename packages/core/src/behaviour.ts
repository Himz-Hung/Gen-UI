const KINDS = ['size', 'keepsSize', 'emits', 'neverEmits', 'role', 'key', 'rendersNothing', 'minTarget'];
const LAYOUT = new Set(['size', 'keepsSize', 'minTarget']);
const levelOf = (c: Check) => c.level ?? (c.kind === 'minTarget' ? 'warn' : 'error');
const GENERATED = 'GENERATED by fw verify';

